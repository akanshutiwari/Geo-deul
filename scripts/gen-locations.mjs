// Generates the on-chain location table (Rust) and the app's name lookup (TS)
// from locations.json so both sides always agree on index -> coordinates.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const locs = JSON.parse(readFileSync(new URL("../locations.json", import.meta.url)));
const micro = (d) => Math.round(d * 1e6);

const rust = `// @generated by scripts/gen-locations.mjs — do not edit by hand.
/// Curated (lat, lng) pool in micro-degrees. VRF picks an index and adds jitter.
pub const LOCATIONS: [(i32, i32); ${locs.length}] = [
${locs.map(([n, , lat, lng]) => `    (${micro(lat)}, ${micro(lng)}), // ${n}`).join("\n")}
];
`;
writeFileSync(new URL("../programs/geo-duels/src/locations.rs", import.meta.url), rust);

mkdirSync(new URL("../app/src/lib/", import.meta.url), { recursive: true });
const ts = `// @generated by scripts/gen-locations.mjs — do not edit by hand.
export interface PoolLocation { name: string; country: string; lat: number; lng: number }
export const LOCATIONS: PoolLocation[] = ${JSON.stringify(
  locs.map(([name, country, lat, lng]) => ({ name, country, lat, lng })),
  null,
  2,
)};
`;
writeFileSync(new URL("../app/src/lib/locations.ts", import.meta.url), ts);
console.log(`wrote ${locs.length} locations`);
